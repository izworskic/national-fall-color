function nearestCameras(milepost, limit = 5) {
  const mp = Number(milepost);
  return CAMERAS
    .map((camera) => ({ ...camera, distance_mileposts: Number.isFinite(mp) ? Math.round(Math.abs(camera.milepost - mp) * 10) / 10 : null }))
    .sort((a, b) => {
      if (a.distance_mileposts == null && b.distance_mileposts == null) return a.milepost - b.milepost;
      if (a.distance_mileposts == null) return 1;
      if (b.distance_mileposts == null) return -1;
      return a.distance_mileposts - b.distance_mileposts;
    })
    .slice(0, Math.max(1, Math.min(8, Number(limit) || 5)));
}

